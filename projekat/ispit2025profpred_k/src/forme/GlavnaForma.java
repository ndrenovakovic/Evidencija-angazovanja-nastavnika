    private void jButtonPrikaziOstaleProfesoreActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonPrikaziOstaleProfesoreActionPerformed
        int selektovaniRed = jTableAngazovanja.getSelectedRow();
        if (selektovaniRed != -1) {
            ModelTabeleAngazovanje mta = (ModelTabeleAngazovanje) jTableAngazovanja.getModel();
            Angazovanje a = mta.getLista().get(selektovaniRed);
            Predmet p = a.getPredmet();

            KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.VRATI_ANGAZOVANJA_NA_PREDMETU, p);
            Komunikacija.getInstance().posaljiZahtev(kz);
            //obrada zahteva
            ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();

            List<Angazovanje> lista = (List<Angazovanje>) so.getOdgovor();
            ModelTabeleAngazovanje2 mta2 = new ModelTabeleAngazovanje2(lista);
            jTableProfesoriNaPredmetu.setModel(mta2);
        }
    }//GEN-LAST:event_jButtonPrikaziOstaleProfesoreActionPerformed

    private void jButtonObrisiAngazovanjeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonObrisiAngazovanjeActionPerformed
        int selektovaniRed = jTableProfesoriNaPredmetu.getSelectedRow();
        if (selektovaniRed != -1) {
            ModelTabeleAngazovanje2 mta2 = (ModelTabeleAngazovanje2) jTableProfesoriNaPredmetu.getModel();
            Angazovanje a = mta2.getLista().get(selektovaniRed);

            KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.OBRISI_ANGAZOVANJE, a);
            Komunikacija.getInstance().posaljiZahtev(kz);
            //obrada na serveru
            ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
            boolean uspeh = (boolean) so.getOdgovor();
            if (uspeh) {
                popuniFormu();
                ModelTabeleAngazovanje2 mta21 = new ModelTabeleAngazovanje2(new ArrayList<>());
                jTableProfesoriNaPredmetu.setModel(mta21);
            } else {
                JOptionPane.showMessageDialog(this, "Greska pri brisanju");
            }
        }
    }//GEN-LAST:event_jButtonObrisiAngazovanjeActionPerformed

