    private void jButtonDodajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDodajActionPerformed
        Predmet predmet = (Predmet) jComboBoxPredmet.getSelectedItem();
        Profesor profesor = (Profesor) jComboBoxProfesor.getSelectedItem();
        TipAngazovanja tip = (TipAngazovanja) jComboBoxTip.getSelectedItem();

        Angazovanje angazovanje = new Angazovanje(-1, profesor, predmet, tip);
        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.DODAJ_ANGAZOVANJE, angazovanje);
        Komunikacija.getInstance().posaljiZahtev(kz);

        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        boolean uspeh = (boolean) so.getOdgovor();
        
        if (uspeh) {
            JOptionPane.showMessageDialog(this, "Uspesno dodavanje angazovanja");
            this.dispose();
        } else {
            JOptionPane.showMessageDialog(this, "Greska pri dodavanju");
        }
    }//GEN-LAST:event_jButtonDodajActionPerformed


