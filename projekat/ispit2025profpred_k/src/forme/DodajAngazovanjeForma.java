    private void popuniComboBoxeve() {
        KlijentskiZahtev kz = new KlijentskiZahtev(Operacije.VRATI_PREDMETE, null);
        Komunikacija.getInstance().posaljiZahtev(kz);

        ServerskiOdgovor so = Komunikacija.getInstance().primiOdgovor();
        List<Predmet> predmeti = (List<Predmet>) so.getOdgovor();

        for (Predmet predmet : predmeti) {
            jComboBoxPredmet.addItem(predmet);
        }

        KlijentskiZahtev kz2 = new KlijentskiZahtev(Operacije.VRATI_PROFESORE, null);
        Komunikacija.getInstance().posaljiZahtev(kz2);

        ServerskiOdgovor so1 = Komunikacija.getInstance().primiOdgovor();
        List<Profesor> profesori = (List<Profesor>) so1.getOdgovor();

        for (Profesor profesor : profesori) {
            jComboBoxProfesor.addItem(profesor);
        }

        for (TipAngazovanja tip : TipAngazovanja.values()) {
            jComboBoxTip.addItem(tip);
        }
    }
